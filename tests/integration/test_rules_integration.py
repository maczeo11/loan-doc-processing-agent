def test_integration_bank_arithmetic_mismatch_in_dossier(tmp_path):
    """Injected bank statement arithmetic mismatch triggers RULE-BANK-01 flag without altering other rules."""
    manifest = generate_dossier(seed=208, scenario="clean", output_dir=str(tmp_path))

    # Tamper closing balance by ₹5,000 to induce arithmetic discrepancy
    manifest["financial_ground_truth"]["bank_closing_balance"] += 5000.0

    findings = evaluate_dossier_rules(dossier_manifest=manifest)
    f_map = findings_to_dict(findings)

    assert f_map["RULE-BANK-01"].verdict == "flag"
    assert "Bank statement arithmetic discrepancy" in f_map["RULE-BANK-01"].reason
    assert "exceeds ₹0.05 tolerance" in f_map["RULE-BANK-01"].reason

    # Other rules remain completely unaffected
    assert f_map["RULE-COMP-01"].verdict == "pass"
    assert f_map["RULE-INC-01"].verdict == "pass"
    assert f_map["RULE-TAX-01"].verdict == "pass"
    assert f_map["RULE-ID-01"].verdict == "pass"


def test_integration_all_rules_independent_and_non_overwriting(tmp_path):
    """Verifies that all 5 findings are independent typed Finding models with unique IDs and provenance."""
    manifest = generate_dossier(seed=209, scenario="clean", output_dir=str(tmp_path))
    findings = evaluate_dossier_rules(dossier_manifest=manifest)

    assert len(findings) == 5
    rule_ids = [f.rule_id for f in findings]
    assert len(set(rule_ids)) == 5  # No duplicate rule IDs

    expected_ids = ["RULE-COMP-01", "RULE-INC-01", "RULE-TAX-01", "RULE-ID-01", "RULE-BANK-01"]
    assert rule_ids == expected_ids

    for finding in findings:
        assert isinstance(finding, Finding)
        assert finding.verdict in ("pass", "flag", "unknown")
        assert len(finding.reason) > 0
        assert finding.policy_version == "v1.0"
        assert isinstance(finding.supporting_evidence, list)
