"""
Integration Tests for Member 4 Deterministic Rules Engine.
HUMAN-ONLY ZONE: Owned by Member 4 (Sravanthi).

Validates end-to-end integration across all 5 deterministic rules:
  1. RULE-COMP-01 (Completeness)
  2. RULE-INC-01 (Salary vs Bank Credit)
  3. RULE-TAX-01 (Tax Return vs Stated Income)
  4. RULE-ID-01 (Cross-Document Identity)
  5. RULE-BANK-01 (Bank Statement Arithmetic)

Verifies that actual evaluated rule findings strictly match expected ground-truth outcomes
across all controlled anomaly scenarios generated by scripts/generate_dossiers.py:
  - clean
  - missing_payslip / missing_itr
  - salary_mismatch
  - tax_mismatch
  - identity_mismatch
  - multiple_inconsistencies
"""

from typing import Dict

from core.contracts.findings import Finding
from core.rules import evaluate_dossier_rules, findings_to_dict
from scripts.generate_dossiers import generate_dossier


def test_integration_clean_dossier(tmp_path):
    """Clean dossier: All 5 rules must independently evaluate to PASS with full provenance."""
    manifest = generate_dossier(seed=201, scenario="clean", output_dir=str(tmp_path))
    findings = evaluate_dossier_rules(dossier_manifest=manifest)

    assert len(findings) == 5
    f_map: Dict[str, Finding] = findings_to_dict(findings)

    expected = manifest["expected_rule_outcomes"]
    for rule_id, expected_verdict in expected.items():
        assert rule_id in f_map, f"Missing finding for {rule_id}"
        assert f_map[rule_id].verdict == expected_verdict, (
            f"Verdict mismatch for {rule_id}: got {f_map[rule_id].verdict}, expected {expected_verdict}"
        )
        assert f_map[rule_id].policy_version == "v1.0"
        assert len(f_map[rule_id].supporting_evidence) > 0

    assert f_map["RULE-COMP-01"].verdict == "pass"
    assert f_map["RULE-INC-01"].verdict == "pass"
    assert f_map["RULE-TAX-01"].verdict == "pass"
    assert f_map["RULE-ID-01"].verdict == "pass"
    assert f_map["RULE-BANK-01"].verdict == "pass"


